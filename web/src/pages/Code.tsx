import { downloadZip, generateFiles } from '../demo/codegen.ts'
import { stats } from '../demo/data.ts'
import { useStore } from '../demo/store.tsx'
import { Button, Empty, PageHead, Status } from '../ui.tsx'
import { CodeBrowser, type Go } from './shared.tsx'

export function CodePage({ go }: { go: Go }) {
  const { t, latest, startRun } = useStore()
  const ready = latest?.generated
  const s = ready ? stats(latest.services) : null
  return (
    <>
      <PageHead
        title={t('Code', 'Code')}
        lead={t('Der erzeugte Terraform-Code des letzten Laufs.', 'The Terraform code generated by the latest run.')}
        actions={ready && (
          <Button icon="download" onClick={() => downloadZip(generateFiles(latest.services, latest.verified))}>
            {t('Als ZIP herunterladen', 'Download as ZIP')}
          </Button>
        )}
      />
      {ready && s ? (
        <>
          <div className="summary">
            {latest.verified
              ? <Status tone="ok">Zero-diff</Status>
              : <Status tone="info">{t('Noch nicht geprüft', 'Not verified yet')}</Status>}
            <span>{s.moduleCalls} {t('Modul-Aufrufe', 'module calls')}</span>
            <span>{s.raw} {t('Raw-Fallbacks', 'raw fallbacks')}</span>
            <span>{s.imports} {t('Import-Blöcke', 'import blocks')}</span>
          </div>
          <CodeBrowser services={latest.services} verified={latest.verified} />
        </>
      ) : (
        <Empty
          icon="code" title={t('Noch kein Code erzeugt', 'No code generated yet')}
          text={t('Der Code entsteht im Lauf nach der Inspektion.', 'Code is generated in a run after the inspection.')}
          action={<Button variant="primary" iconRight="arrowRight" onClick={() => { startRun(); go('/run') }}>{t('Zum Lauf', 'Go to run')}</Button>}
        />
      )}
    </>
  )
}
