import { CALLS, MODULES, deviationFor, resourcesFor, type ModuleCall, type Service } from './data.ts'

export interface TfFile {
  name: string
  content: string
}

const HEADER = '# Generated by Orefy. Review before you apply.\n\n'

function block(head: string, args: [string, string][]): string {
  const width = Math.max(...args.map(([k]) => k.length))
  return `${head} {\n${args.map(([k, v]) => `  ${k.padEnd(width)} = ${v}`).join('\n')}\n}\n`
}

function moduleBlock(call: ModuleCall, verified: boolean, fixKey: string | undefined): string {
  const mod = MODULES[call.module]
  // The input the verify loop corrects is missing until verification ran.
  const inputs = call.inputs.filter((x) => !x.fix || verified || x.key !== fixKey)
  return block(`module "${call.name}"`, [
    ['source', `"${mod.source}"`],
    ['version', `"${mod.version}"`],
    ...inputs.map((x): [string, string] => [x.key, x.value]),
  ])
}

export function generateFiles(services: Service[], verified: boolean): TfFile[] {
  const resources = resourcesFor(services).filter((r) => r.managed === 'clickops')
  const calls = CALLS.filter((c) => services.includes(c.service))
  const deviation = deviationFor(services)
  const fixKey = deviation?.input.split(' = ')[0]
  const fixCall = deviation?.address.split('.')[1]

  const files: TfFile[] = [
    {
      name: 'versions.tf',
      content: `${HEADER}terraform {\n  required_version = ">= 1.5.0"\n\n  required_providers {\n    aws = {\n      source  = "hashicorp/aws"\n      version = "~> 6.0"\n    }\n  }\n}\n`,
    },
    { name: 'providers.tf', content: `${HEADER}provider "aws" {\n  region = var.region\n}\n` },
    {
      name: 'variables.tf',
      content:
        `${HEADER}variable "region" {\n  type        = string\n  description = "AWS region of the imported resources."\n  default     = "eu-central-1"\n}\n` +
        (resources.some((r) => r.raw?.type === 'aws_key_pair')
          ? `\nvariable "ops_public_key" {\n  type        = string\n  description = "Public key material of the ops-2023 key pair. AWS does not return it."\n}\n`
          : ''),
    },
  ]

  const byFile = new Map<string, string[]>()
  const add = (file: string, text: string) => byFile.set(file, [...(byFile.get(file) ?? []), text])
  for (const call of calls) {
    add(MODULES[call.module].file, moduleBlock(call, verified, call.name === fixCall ? fixKey : undefined))
  }
  for (const r of resources) {
    if (r.raw) {
      add(r.raw.file, `# Raw fallback: no terraform-aws-modules match for ${r.raw.type}\n` + block(`resource "${r.raw.type}" "${r.raw.name}"`, r.raw.args))
    }
  }
  for (const name of ['network.tf', 'compute.tf', 'storage.tf', 'iam.tf', 'messaging.tf']) {
    const parts = byFile.get(name)
    if (parts) files.push({ name, content: HEADER + parts.join('\n') })
  }

  files.push({
    name: 'imports.tf',
    content:
      '# Generated by Orefy. Safe to delete after the first successful apply.\n\n' +
      resources.map((r) => `import {\n  to = ${r.address}\n  id = "${r.id}"\n}\n`).join('\n'),
  })
  return files
}

/** Minimal store-only ZIP writer, enough to hand the generated files to the visitor. */
export function zip(files: TfFile[]): Blob {
  const enc = new TextEncoder()
  const table = new Uint32Array(256).map((_, n) => {
    let c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    return c >>> 0
  })
  const crc32 = (bytes: Uint8Array) => {
    let c = 0xffffffff
    for (const b of bytes) c = table[(c ^ b) & 0xff] ^ (c >>> 8)
    return (c ^ 0xffffffff) >>> 0
  }
  const parts: Uint8Array[] = []
  const central: Uint8Array[] = []
  let offset = 0
  for (const f of files) {
    const name = enc.encode(f.name)
    const data = enc.encode(f.content)
    const crc = crc32(data)
    const local = new DataView(new ArrayBuffer(30))
    local.setUint32(0, 0x04034b50, true)
    local.setUint16(4, 20, true)
    local.setUint16(6, 0x0800, true)
    local.setUint32(14, crc, true)
    local.setUint32(18, data.length, true)
    local.setUint32(22, data.length, true)
    local.setUint16(26, name.length, true)
    const cd = new DataView(new ArrayBuffer(46))
    cd.setUint32(0, 0x02014b50, true)
    cd.setUint16(4, 20, true)
    cd.setUint16(6, 20, true)
    cd.setUint16(8, 0x0800, true)
    cd.setUint32(16, crc, true)
    cd.setUint32(20, data.length, true)
    cd.setUint32(24, data.length, true)
    cd.setUint16(28, name.length, true)
    cd.setUint32(42, offset, true)
    parts.push(new Uint8Array(local.buffer), name, data)
    central.push(new Uint8Array(cd.buffer), name)
    offset += 30 + name.length + data.length
  }
  const cdSize = central.reduce((n, p) => n + p.length, 0)
  const end = new DataView(new ArrayBuffer(22))
  end.setUint32(0, 0x06054b50, true)
  end.setUint16(8, files.length, true)
  end.setUint16(10, files.length, true)
  end.setUint32(12, cdSize, true)
  end.setUint32(16, offset, true)
  return new Blob([...parts, ...central, new Uint8Array(end.buffer)] as BlobPart[], { type: 'application/zip' })
}

export function downloadZip(files: TfFile[], filename = 'orefy-import.zip') {
  const url = URL.createObjectURL(zip(files))
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}
