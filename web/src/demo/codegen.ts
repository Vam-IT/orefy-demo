import { CALLS, DEPLOY_ROLE_ARN, MODULES, PLAN_ROLE_ARN, STATE_BUCKET, TERRAFORM_VERSION, deviationFor, resourcesFor, type ModuleCall, type Provider, type Service } from './data.ts'

export interface TfFile {
  name: string
  content: string
}

const HEADER = '# Generated by Orefy. Review before you apply.\n\n'

function block(head: string, args: [string, string][]): string {
  const width = Math.max(...args.map(([k]) => k.length))
  return `${head} {\n${args.map(([k, v]) => `  ${k.padEnd(width)} = ${v}`).join('\n')}\n}\n`
}

function moduleBlock(call: ModuleCall, verified: boolean, fixKey: string | undefined): string {
  const mod = MODULES[call.module]
  // The input the verify loop corrects is missing until verification ran.
  const inputs = call.inputs.filter((x) => !x.fix || verified || x.key !== fixKey)
  return block(`module "${call.name}"`, [
    ['source', `"${mod.source}"`],
    ['version', `"${mod.version}"`],
    ...inputs.map((x): [string, string] => [x.key, x.value]),
  ])
}

export function generateFiles(services: Service[], verified: boolean): TfFile[] {
  const resources = resourcesFor(services).filter((r) => r.managed === 'clickops')
  const calls = CALLS.filter((c) => services.includes(c.service))
  const deviation = deviationFor(services)
  const fixKey = deviation?.input.split(' = ')[0]
  const fixCall = deviation?.address.split('.')[1]

  const files: TfFile[] = [
    {
      name: 'versions.tf',
      content: `${HEADER}terraform {\n  required_version = ">= 1.5.0"\n\n  required_providers {\n    aws = {\n      source  = "hashicorp/aws"\n      version = "~> 6.0"\n    }\n  }\n}\n`,
    },
    { name: 'providers.tf', content: `${HEADER}provider "aws" {\n  region = var.region\n}\n` },
    {
      name: 'variables.tf',
      content:
        `${HEADER}variable "region" {\n  type        = string\n  description = "AWS region of the imported resources."\n  default     = "eu-central-1"\n}\n` +
        (resources.some((r) => r.raw?.type === 'aws_key_pair')
          ? `\nvariable "ops_public_key" {\n  type        = string\n  description = "Public key material of the ops-2023 key pair. AWS does not return it."\n}\n`
          : ''),
    },
  ]

  const byFile = new Map<string, string[]>()
  const add = (file: string, text: string) => byFile.set(file, [...(byFile.get(file) ?? []), text])
  for (const call of calls) {
    add(MODULES[call.module].file, moduleBlock(call, verified, call.name === fixCall ? fixKey : undefined))
  }
  for (const r of resources) {
    if (r.raw) {
      add(r.raw.file, `# Raw fallback: no terraform-aws-modules match for ${r.raw.type}\n` + block(`resource "${r.raw.type}" "${r.raw.name}"`, r.raw.args))
    }
  }
  for (const name of ['network.tf', 'compute.tf', 'storage.tf', 'iam.tf', 'messaging.tf']) {
    const parts = byFile.get(name)
    if (parts) files.push({ name, content: HEADER + parts.join('\n') })
  }

  files.push({
    name: 'imports.tf',
    content:
      '# Generated by Orefy. Safe to delete after the first successful apply.\n\n' +
      resources.map((r) => `import {\n  to = ${r.address}\n  id = "${r.id}"\n}\n`).join('\n'),
  })
  return files
}

